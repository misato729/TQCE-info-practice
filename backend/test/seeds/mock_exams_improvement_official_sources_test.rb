require "test_helper"
require_relative "../support/improvement_revision_20261017"

class MockExamsImprovementOfficialSourcesTest < ActiveSupport::TestCase
  SOURCE_PATH = Rails.root.join("test/fixtures/improvement_revision_20261017_sources.json")
  SOURCES = JSON.parse(File.read(SOURCE_PATH)).freeze
  SOURCE_SHA256 = "bb55da2605eb3202423d56c5ec2bed85af57f4a72c90ef78581b20cbf98aab21".freeze
  BLANKS = %w[① ② ③ ④ ⑤ ⑥].freeze

  setup do
    @questions = QuestionSeedSync.collect { (1..50).each { |exam| load Rails.root.join("db/seeds/mock_exam_#{exam}.rb") } }
      .to_h { |entry| ["#{entry[:exam_number]}-#{entry[:attributes][:question_number]}", entry[:attributes]] }
  end

  test "今回の原文問題全件を独立した公式本文と物理頁へ対応させる" do
    assert_equal SOURCE_SHA256, Digest::SHA256.file(SOURCE_PATH).hexdigest
    assert_includes SOURCES.fetch("provenance"), "Not generated by restoring answers"
    expected = ImprovementRevision20261017::DATA.fetch("previous_entries").keys.select do |id|
      question = @questions.fetch(id)
      prompt = question[:content_blocks].first.fetch(:text)
      (prompt.include?("からの抜粋") || prompt.include?("の条文である")) &&
        question[:content_blocks].any? { |block| block[:type] == "fill_in_quote" && block[:text].match?(/\{\{[^{}]+\}\}/) } &&
        question[:choices].first[:content_blocks].first[:type] == "fill_in_choice"
    end
    assert expected.any?, "原文検査対象0問を成功としない"
    assert_equal expected.sort, SOURCES.fetch("locations").keys.sort
    SOURCES.fetch("documents").each do |name, document|
      assert_match(/\A[0-9a-f]{64}\z/, document.fetch("download_sha256"), name)
      assert_match(/\Ahttps:\/\/(?:www\.mext\.go\.jp|laws\.e-gov\.go\.jp)\//, document.fetch("url"), name)
      assert document.fetch(document["kind"] == "law" ? "articles" : "pages").present?, name
    end
  end

  test "全候補を代入して正答行だけが連続した公式原文に一致する" do
    count = 0
    SOURCES.fetch("locations").each do |id, location|
      question = @questions.fetch(id)
      document = SOURCES.fetch("documents").fetch(location.fetch("document"))
      quotes = question[:content_blocks].select { |block| block[:type] == "fill_in_quote" && block[:text].include?("{{") }.map { |block| block.fetch(:text) }
      assert quotes.any?, id
      labels = quotes.join("\n").scan(/\{\{([^{}]+)\}\}/).flatten.uniq
      assert_equal BLANKS.first(labels.size), labels, id
      question.fetch(:choices).each do |choice|
        cells = choice.fetch(:content_blocks).first.fetch(:cells)
        assert_equal labels.size, cells.size, id
        terms = BLANKS.zip(cells).to_h
        restored = quotes.map { |quote| quote.gsub(/\{\{([^{}]+)\}\}/) { terms.fetch(Regexp.last_match(1)) } }
        matches = restored.each_with_index.all? do |quote, index|
          if location.fetch("kind") == "law"
            quote.split(/(?=^第[0-9]+条)/).reject(&:blank?).all? do |chunk|
              number = chunk[/\A第([0-9]+)条(?:の([0-9]+))?/, 1]
              branch = chunk[/\A第([0-9]+)条(?:の([0-9]+))?/, 2]
              article_id = [number, branch].compact.join("_")
              article_id = location.fetch("articles").sole if article_id.empty? && location.fetch("heading_optional", false)
              assert_includes location.fetch("articles"), article_id, id
              original = document.fetch("articles").find { |article| article.fetch("number") == article_id }.fetch("body")
              normalize(original).include?(normalize(without_law_numbers(chunk)))
            end
          else
            pages = location.fetch("quote_pages").fetch(index)
            assert_includes [1, 2, 3], pages.size, id
            pages.each_cons(2) { |left, right| assert_equal left + 1, right, id }
            %w[normalized_page_text normalized_body_text normalized_body_crop].any? do |field|
              pages.map { |page| document.fetch("pages").fetch(page.to_s).fetch(field) }.join.include?(normalize(quote))
            end
          end
        end
        assert_equal choice.fetch(:correct), matches, "#{id} #{choice[:label]}: 原文全体の連続性"
        count += 1
      end
    end
    assert_equal SOURCES.fetch("locations").size * 4, count
  end

  private

  def normalize(text)
    text.unicode_normalize(:nfkc).gsub(/、|，/, ",").gsub("•", "・").gsub(/\[\*\d+\]/, "")
      .gsub(/[[:space:]\u0000-\u001f\u007f]+/, "").gsub("涵かん養", "涵養").gsub("拓ひらく", "拓く")
      .gsub("俯ふ瞰かん", "俯瞰").gsub("信憑ぴょう性", "信憑性").gsub("Entity\ufffeRelationship", "Entity-Relationship")
  end

  def without_law_numbers(text)
    text.lines.filter_map do |line|
      next if line.match?(/\A\s*第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?(?:第[0-9０-９一二三四五六七八九十]+項)?(?:第[0-9０-９一二三四五六七八九十]+号)?(?:[〜～・]第?[0-9０-９一二三四五六七八九十]+項)?\s*\z/)
      line.strip.sub(/\A第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?(?:第[0-9０-９一二三四五六七八九十]+項)?(?:第[0-9０-９一二三四五六七八九十]+号)?[\s　]*/, "")
        .sub(/\A[0-9０-９一二三四五六七八九十]+[\s　]+/, "")
    end.join("\n")
  end
end
