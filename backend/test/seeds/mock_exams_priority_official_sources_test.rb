require "test_helper"
require_relative "../support/priority_revision_20261017"

class MockExamsPriorityOfficialSourcesTest < ActiveSupport::TestCase
  SOURCE_PATH = Rails.root.join("test/fixtures/priority_revision_20261017_sources.json")
  SOURCES = JSON.parse(File.read(SOURCE_PATH)).freeze
  SOURCE_SHA256 = "d9d12f8636eb8d8079554d8d6e714e8412b9fb5e300fb930014e687cf0513691".freeze
  KEYS = %w[
    1-10 1-11 1-16 1-3 1-4 1-5 10-15 10-8 10-9
    11-16 11-17 11-18 11-5 11-8 12-16 12-17 12-18
    13-16 13-17 13-18 13-9 14-17 14-18 14-8 15-17 15-18 15-9
    16-8 2-17 2-3 2-4 2-7 24-9 25-8 3-16 3-17 3-4 3-5
    38-5 4-17 5-4 5-6 6-16 6-18 7-11 7-17 8-10 8-8 9-11 9-16 9-4
  ].sort.freeze
  BLANKS = %w[① ② ③ ④ ⑤ ⑥].freeze

  setup do
    @all = QuestionSeedSync.collect { (1..50).each { |exam| load Rails.root.join("db/seeds/mock_exam_#{exam}.rb") } }
    @questions = @all.to_h { |entry| ["#{entry[:exam_number]}-#{entry[:attributes][:question_number]}", entry[:attributes]] }
  end

  test "原文五十一問の独立した公式資料と物理頁を固定する" do
    assert_equal SOURCE_SHA256, Digest::SHA256.file(SOURCE_PATH).hexdigest, "失敗を受理するために原典を正答から生成し直さない"
    assert_equal 51, KEYS.size
    assert_equal KEYS, SOURCES.fetch("locations").keys.sort
    assert_includes SOURCES.fetch("provenance"), "Not generated by restoring"
    actual = PriorityRevision20261017::DATA.fetch("previous_entries").keys.select do |id|
      question = @questions.fetch(id)
      prompt = question[:content_blocks].first.fetch(:text)
      (prompt.include?("からの抜粋") || prompt.include?("の条文である")) &&
        question[:content_blocks].any? { |block| block[:type] == "fill_in_quote" && block[:text].match?(/\{\{[^{}]+\}\}/) } &&
        question[:choices].first[:content_blocks].first[:type] == "fill_in_choice"
    end
    assert_equal KEYS, actual.sort, "抽出漏れや空欄削除を成功扱いにしない"
    SOURCES.fetch("documents").each do |name, document|
      assert_match(/\A[0-9a-f]{64}\z/, document.fetch("download_sha256"), name)
      assert_match(/\Ahttps:\/\/(?:www\.mext\.go\.jp|laws\.e-gov\.go\.jp)\//, document.fetch("url"), name)
      assert document.fetch(document["kind"] == "law" ? "articles" : "pages").present?, name
    end
    assert_includes SOURCES.fetch("documents").fetch("school_20260401").fetch("url"), "/20260401_507AC0000000068"
  end

  test "二百四候補を原典の連続した本文へ代入して正答だけが一致する" do
    count = 0
    KEYS.each do |id|
      question = @questions.fetch(id)
      location = SOURCES.fetch("locations").fetch(id)
      document = SOURCES.fetch("documents").fetch(location.fetch("document"))
      quotes = question[:content_blocks].select { |block| block[:type] == "fill_in_quote" }
      assert_equal 1, quotes.size, id
      quote = quotes.first.fetch(:text)
      assert_no_match(/中略|略称に置換/, quote, id)
      labels = quote.scan(/\{\{([^{}]+)\}\}/).flatten.uniq
      assert_equal BLANKS.first(labels.size), labels, id
      originals = if location.fetch("kind") == "law"
        [normalize(document.fetch("articles").find { |article| article.fetch("number") == location.fetch("article") }.fetch("body"))]
      else
        pages = location.fetch("pdf_pages")
        assert_includes [1, 2, 3], pages.size, id
        pages.each_cons(2) { |left, right| assert_equal left + 1, right, id }
        %w[normalized_page_text normalized_body_text normalized_body_crop].map do |field|
          pages.map { |page| document.fetch("pages").fetch(page.to_s).fetch(field) }.join
        end
      end
      question.fetch(:choices).each do |choice|
        cells = choice.fetch(:content_blocks).first.fetch(:cells)
        assert_equal labels.size, cells.size, id
        terms = BLANKS.zip(cells).to_h
        restored = quote.gsub(/\{\{([^{}]+)\}\}/) { terms.fetch(Regexp.last_match(1)) }
        restored = without_law_numbers(restored) if location.fetch("kind") == "law"
        matches = originals.any? { |original| original.include?(normalize(restored)) }
        assert_equal choice.fetch(:correct), matches, "#{id} #{choice[:label]}: 原文全体の連続性"
        count += 1
      end
    end
    assert_equal 204, count
  end

  private

  def normalize(text)
    text.unicode_normalize(:nfkc).gsub(/、|，/, ",").gsub("•", "・").gsub(/\[\*\d+\]/, "")
      .gsub(/[[:space:]\u0000-\u001f\u007f]+/, "")
      .gsub("涵かん養", "涵養").gsub("拓ひらく", "拓く").gsub("俯ふ瞰かん", "俯瞰")
      .gsub("信憑ぴょう性", "信憑性").gsub("Entity\ufffeRelationship", "Entity-Relationship")
  end

  def without_law_numbers(text)
    text.lines.filter_map do |line|
      next if line.match?(/\A\s*第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?(?:第[0-9０-９一二三四五六七八九十]+項)?(?:[〜～・]第?[0-9０-９一二三四五六七八九十]+項)?\s*\z/)
      line.strip.sub(/\A第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?(?:第[0-9０-９一二三四五六七八九十]+項)?[\s　]*/, "")
        .sub(/\A[0-9０-９一二三四五六七八九十]+[\s　]+/, "")
    end.join("\n")
  end
end
