require "test_helper"
require "digest"

class MockExams41To50OfficialSourcesTest < ActiveSupport::TestCase
  EXAMS = (41..50).to_a.freeze
  BLANKS = %w[① ② ③ ④].freeze
  LAW_KEYS = (EXAMS.flat_map { |exam| ["#{exam}-4", "#{exam}-5"] } +
    %w[41-3 45-3 46-3 49-3]).sort.freeze
  PDF_KEYS = (EXAMS.flat_map { |exam| (6..10).map { |number| "#{exam}-#{number}" } } +
    [41, 42, 43, 44, 46, 47, 48, 49].map { |exam| "#{exam}-11" } +
    %w[44-15 50-15] +
    EXAMS.flat_map { |exam| (16..18).map { |number| "#{exam}-#{number}" } } -
    %w[42-18 48-18]).sort.freeze
  LITERAL_KEYS = (LAW_KEYS + PDF_KEYS).sort.freeze
  SOURCE_PATH = Rails.root.join("test/fixtures/mock_exams_41_to_50_official_sources.json")
  SOURCES = JSON.parse(File.read(SOURCE_PATH)).freeze
  # These digests identify the independently downloaded official documents,
  # not text reconstructed from the seeded correct choices.
  DOWNLOAD_HASHES = {
    "basic" => "cb1d7aebb813a3784739f27130f9b47d44feb830dd1d87e14728bed343d74480",
    "school" => "c7753e284fa7694378fccc4b9da74df683888417b3f999242d012d86df80ed1a",
    "teacher" => "7731cc3977164558bb9c85757dcf9d75972e979fa6f23a9458f48805b9eac896",
    "local" => "a57f2a96afac149fd7fc5296195f7133649f59761b592d7a121365f3d0331565",
    "curriculum" => "59ef17a825bd11a4fa39ed2cc1f27033c83a95e4e93f0f8a821a65e063bb2512",
    "inquiry" => "e012ec38bed88c22948f8a47c23948ce1f13ffdcef8d48188e2d5713cc68ad50",
    "activities" => "443d8d91bd7ce9f8e3122f71822269130a6204910b5ece9200d152751b49655e",
    "guidance" => "d2ed3339c0e1098baa177ec0b1ebf435e344310daa4278a1fc3c601e2165e8a0",
    "report" => "5affb870ae87af1c6272b15b008fea88547ccc50141e20e38fd13bb128f9f39c",
    "information" => "0a95db55b9ec0570ac4b47586d9f6342c82a0ec5e7c0b071111208ae6e09d443",
  }.freeze
  LAW_ARTICLE_COUNTS = { "basic" => 18, "school" => 161, "teacher" => 43, "local" => 106 }.freeze

  setup do
    entries = QuestionSeedSync.collect { EXAMS.each { |exam| load Rails.root.join("db/seeds/mock_exam_#{exam}.rb") } }
    @questions = entries.to_h do |entry|
      ["#{entry.fetch(:exam_number)}-#{entry.fetch(:attributes).fetch(:question_number)}", entry.fetch(:attributes)]
    end
  end

  test "原典穴埋め百十二問を法令二十四問と公式PDF八十八問へ厳密に対応付ける" do
    assert_equal "1b31567a128c631690945d25b4ca3fb20f15f19f94699e7167865a225918d695",
      Digest::SHA256.file(SOURCE_PATH).hexdigest, "独立原典fixtureを正答復元から作り直さない"
    assert_equal "6fad11b9d3c483b1dbabdfc175bf041e633e045b2756608c8a76c0f474bf4424",
      Digest::SHA256.hexdigest(JSON.generate(SOURCES.fetch("locations"))), "資料及び物理頁の固定対応"
    assert_equal 200, @questions.size
    assert_equal 24, LAW_KEYS.size
    assert_equal 88, PDF_KEYS.size
    assert_equal 112, LITERAL_KEYS.size
    assert_equal LITERAL_KEYS, SOURCES.fetch("locations").keys.sort
    actual = @questions.select do |_id, question|
      question.fetch(:content_blocks).any? do |block|
        block[:type] == "fill_in_quote" && block.fetch(:text).match?(/\{\{[^{}]+\}\}/)
      end
    end.keys.sort
    assert_equal LITERAL_KEYS, actual, "抽出漏れ・空欄全消去・対象追加を成功扱いにしない"
    assert_equal LAW_KEYS, locations_of_kind("law")
    assert_equal PDF_KEYS, locations_of_kind("pdf")
    assert_equal "2026-10-17", SOURCES.fetch("checked_date")
    assert_includes SOURCES.fetch("normalization"), "Not generated by restoring"
    assert_equal DOWNLOAD_HASHES.keys.sort, SOURCES.fetch("documents").keys.sort
    assert_equal 54, SOURCES.fetch("documents").values.sum { |document| document.fetch("pages", {}).size }
    SOURCES.fetch("documents").each do |name, document|
      assert_equal DOWNLOAD_HASHES.fetch(name), document.fetch("download_sha256"), name
      if LAW_ARTICLE_COUNTS.key?(name)
        assert_equal "law", document.fetch("kind"), name
        assert_match(/\Ahttps:\/\/laws\.e-gov\.go\.jp\/law\/\d+[A-Z]+\d+\z/, document.fetch("url"), name)
        articles = document.fetch("articles")
        assert_equal LAW_ARTICLE_COUNTS.fetch(name), articles.size, name
        assert_equal articles.size, articles.map { |article| article.fetch("number") }.uniq.size, name
        assert articles.all? { |article| article.fetch("body").present? }, name
      else
        assert_equal "pdf", document.fetch("kind"), name
        assert_match(/\Ahttps:\/\/www\.mext\.go\.jp\/content\/.+\.pdf\z/, document.fetch("url"), name)
        assert document.fetch("pages").present?, name
        document.fetch("pages").each do |number, page|
          assert_match(/\A[1-9]\d*\z/, number, name)
          assert_equal %w[normalized_body_crop normalized_page_text], page.keys.sort, "#{name} #{number}"
          page.each_value do |text|
            assert text.present?, "#{name} #{number}"
            assert_equal normalized(text), text, "#{name} #{number} 独立抽出の正規化"
          end
        end
      end
    end
  end

  test "四百四十八候補を独立した原典の連続範囲へ代入し正答行だけ一致する" do
    candidate_count = 0
    LITERAL_KEYS.each do |id|
      question = @questions.fetch(id)
      item = SOURCES.fetch("locations").fetch(id)
      document = SOURCES.fetch("documents").fetch(item.fetch("document"))
      assert_equal item.fetch("kind"), document.fetch("kind"), id
      wording = item.fetch("kind") == "law" && [4, 5].include?(question.fetch(:question_number)) ? "の条文である。" : "からの抜粋である。"
      assert_includes question.fetch(:content_blocks).first.fetch(:text), wording, id
      quotes = question.fetch(:content_blocks).select { |block| block[:type] == "fill_in_quote" }
      assert_equal 1, quotes.size, id
      quote = quotes.first.fetch(:text)
      labels = quote.scan(/\{\{([^{}]+)\}\}/).flatten.uniq.sort
      cells = question.fetch(:choices).first.fetch(:content_blocks).first.fetch(:cells)
      assert_equal BLANKS.first(cells.size), labels, "#{id} 未知・余分な空欄も拒否"
      assert_equal %w[ア イ ウ エ], question.fetch(:choices).map { |choice| choice.fetch(:label) }, id
      originals = original_ranges(item, document, id)
      body = item.fetch("kind") == "law" ? without_law_numbering(quote) : quote
      matches = question.fetch(:choices).map do |choice|
        blocks = choice.fetch(:content_blocks)
        assert_equal 1, blocks.size, "#{id} #{choice.fetch(:label)}"
        assert_equal "fill_in_choice", blocks.first.fetch(:type), id
        assert_equal cells.size, blocks.first.fetch(:cells).size, id
        replacements = BLANKS.zip(blocks.first.fetch(:cells)).to_h
        restored = normalized(body.gsub(/\{\{([^{}]+)\}\}/) { replacements.fetch(Regexp.last_match(1)) })
        assert restored.present?, id
        matched = originals.any? { |original| original.include?(restored) }
        assert_equal choice.fetch(:correct), matched, "#{id} #{choice.fetch(:label)} 原文全体の連続性"
        candidate_count += 1
        matched
      end
      assert_equal 1, matches.count(true), id
    end
    assert_equal 448, candidate_count
  end

  private

  def locations_of_kind(kind)
    SOURCES.fetch("locations").select { |_id, item| item.fetch("kind") == kind }.keys.sort
  end

  def original_ranges(item, document, id)
    if item.fetch("kind") == "law"
      assert_includes @questions.fetch(id).fetch(:source_text), document.fetch("url"), id
      [document.fetch("articles").map { |article| normalized(article.fetch("body")) }.join]
    else
      pages = item.fetch("pdf_pages")
      assert_includes [1, 2], pages.size, id
      pages.each_cons(2) { |left, right| assert_equal left + 1, right, "#{id} 離れた頁を連結しない" }
      assert_includes @questions.fetch(id).fetch(:source_text), "#{document.fetch('url')}#page=#{pages.first}", id
      %w[normalized_page_text normalized_body_crop].map do |field|
        pages.map { |page| document.fetch("pages").fetch(page.to_s).fetch(field) }.join
      end
    end
  end

  def normalized(text)
    text.unicode_normalize(:nfkc).gsub(/[[:space:]\u0000-\u001f]+/, "")
      .gsub("涵かん養", "涵養").gsub("拓ひらく", "拓く")
      .gsub("信憑ぴょう性", "信憑性").gsub("Entity\ufffeRelationship", "Entity-Relationship")
  end

  # The e-Gov fixture keeps the independent full article bodies without the
  # structural article/item labels. Only law quotations lose those labels;
  # PDF item numbers and the source wording are preserved when matching.
  def without_law_numbering(quote)
    quote.lines.filter_map do |line|
      text = line.strip
      next if text.match?(/\A第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?[第0-9０-９一二三四五六七八九十百項号・〜～（）()\s]*\z/)

      text.sub(/\A第[0-9０-９一二三四五六七八九十百]+条(?:の[0-9０-９一二三四五六七八九十]+)?(?:第[0-9０-９一二三四五六七八九十]+項)?[\s　]*/, "")
        .sub(/\A[0-9０-９一二三四五六七八九十]+[\s　]+/, "")
    end.join("\n")
  end
end
